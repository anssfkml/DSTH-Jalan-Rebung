"""Generates index.html (cuts, camera zooms, scene hosts, SFX) and compositions/captions.html
from tools/edl.py. Scene files in compositions/ (hook, lokasi, tawaran, tanah, cta) are hand-written.

    python3 tools/edl.py && python3 tools/build.py
"""
import json, os, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Look: Natural Portrait (skin-soft) + a very light bloom, written by `hyperframes media-treatment`
# and kept in tools/grade.json. Face-only retouch is baked into assets/footage.mp4 by tools/beauty.py.
GRADE = html.escape(json.dumps(json.load(open(os.path.join(ROOT, "tools", "grade.json"))), separators=(",", ":")), quote=True)
d = json.load(open(os.path.join(ROOT, "tools", "edit-timeline.json")))
clips, TOTAL, caps = d["clips"], d["total"], d["captions"]

# Scene hosts: (id, start, end) in edit time. Keep in sync with the scene files.
SCENES = [
    ("hook", 0.0, clips[3]["start"]),
    ("lokasi", clips[3]["start"], clips[6]["start"]),
    ("tawaran", clips[6]["start"], clips[11]["start"]),
    ("tanah", clips[11]["start"], clips[15]["start"]),
    ("cta", clips[15]["start"], TOTAL),
]
CAPTIONS_FROM = clips[3]["start"]  # hook cards already show the spoken price lines

# Sound effects: (visual event time, file, volume). Start = event + 1 frame - file peak.
PEAK = {"pop": 0.12, "whoosh": 0.162, "whoosh-short": 0.162, "click-soft": 0.073,
        "impact-bass-1": 0.073, "whoosh-cinematic": 2.503}
DUR = {"pop": 0.72, "whoosh": 0.575, "whoosh-short": 0.575, "click-soft": 0.366,
       "impact-bass-1": 2.116, "whoosh-cinematic": 5.54}
S = {s[0]: s[1] for s in SCENES}
LANE = {"pop": 4, "click-soft": 5, "whoosh": 6, "whoosh-short": 6, "impact-bass-1": 7, "whoosh-cinematic": 8}
SFX = [
    (1.40, "pop", 0.35),                      # harga "punch"
    (3.45, "impact-bass-1", 0.20),            # cop NET
    (3.80, "whoosh", 0.30),                   # tukar ke kad bulanan
    (5.69, "pop", 0.40),                      # RM2.3K mendarat
    (S["lokasi"] + 0.0, "whoosh-short", 0.28),
    (S["lokasi"] + 0.32, "pop", 0.32),        # pin jatuh
    (S["lokasi"] + 0.50, "click-soft", 0.55), # JALAN REBUNG
    (S["lokasi"] + 2.90, "click-soft", 0.50), # BUKIT KAPAR
    (S["lokasi"] + 4.95, "whoosh", 0.26),     # kad teres
    (S["lokasi"] + 7.37, "pop", 0.38),        # Q1 2027
    (S["tawaran"] + 0.08, "pop", 0.36),       # CASHBACK
    (S["tawaran"] + 1.88, "pop", 0.40),       # ZERO DEPOSIT
    (S["tawaran"] + 2.68, "whoosh-short", 0.28),  # FREEHOLD
    (S["tanah"] + 0.05, "whoosh", 0.24),      # lot dilukis
    (S["tanah"] + 1.18, "click-soft", 0.55),  # 108'
    (S["tanah"] + 2.69, "pop", 0.36),         # tanah belakang
    (S["tanah"] + 4.38, "pop", 0.32),         # 4 bilik
    (S["tanah"] + 5.33, "click-soft", 0.55),  # 3 bilik air
    (S["cta"] + 0.06, "whoosh-cinematic", 0.22),  # BERMINAT? (swell peaks on it)
    (S["cta"] + 1.05, "pop", 0.38),           # butang contact
    (S["cta"] + 3.35, "impact-bass-1", 0.20), # UNIT TERHAD
]


def f(x):
    return f"{x:.3f}".rstrip("0").rstrip(".")


def build_index():
    vids = []
    for c in clips:
        n = c["i"] + 1
        vids.append(
            f'        <video id="v{n:02d}" class="clip" src="assets/footage.mp4" playsinline data-has-audio="true"\n'
            f'          data-start="{f(c["start"])}" data-duration="{f(c["dur"])}" data-media-start="{f(c["src"])}"\n'
            f'          data-fade-in="0.02" data-fade-out="0.03" data-track-index="0"\n'
            f'          data-color-grading="{GRADE}"\n'
            f'          style="z-index:{n}; transform: scale({c["zoom"]})"></video>  <!-- {html.escape(c["note"])} -->'
        )
    hosts = []
    for k, (sid, a, b) in enumerate(SCENES):
        hosts.append(
            f'      <div id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html"\n'
            f'        data-start="{f(a)}" data-duration="{f(b - a)}" data-track-index="2" data-track-kind="graphics"\n'
            f'        data-width="1080" data-height="1920" style="z-index:40"></div>'
        )
    sfx = []
    for k, (t, name, vol) in enumerate(SFX):
        start = max(0.0, t + 1 / 30 - PEAK[name])
        dur = min(DUR[name], TOTAL - start)
        sfx.append(
            f'      <audio id="sfx{k + 1:02d}" class="clip" src="assets/sfx/{name}.mp3" data-start="{f(start)}"'
            f' data-duration="{f(dur)}" data-volume="{vol}" data-track-index="{LANE[name]}"></audio>'
        )

    page = f"""<!doctype html>
<html lang="ms" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <!-- GENERATED by tools/build.py from tools/edl.py: edit the EDL, then rebuild. -->
    <script src="assets/vendor/gsap.min.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: 1080px; height: 1920px; overflow: hidden; background: #000; }}
      body {{ font-family: "Montserrat", sans-serif; }}
      #bump, #cam {{ position: absolute; inset: 0; transform-origin: 50% 30%; }}
      #bump {{ overflow: hidden; }}
      #cam video {{ position: absolute; left: 0; top: 0; width: 1080px; height: 1920px; object-fit: cover;
        transform-origin: 50% 0%; }}
      /* Legibility scrim behind the top text band (cards + captions). */
      #scrim {{ position: absolute; left: 0; top: 0; width: 1080px; height: 900px; z-index: 30; pointer-events: none;
        background: linear-gradient(180deg, rgba(8,10,14,.62) 0%, rgba(8,10,14,.42) 45%, rgba(8,10,14,0) 100%); }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{f(TOTAL)}" data-width="1080" data-height="1920">
      <!-- A-roll: {len(clips)} cuts from one take. Pauses, "Okay guys", "Err..." and filler "So" removed;
           the price lines are moved to the front as the hook. Alternate zooms hide the jump cuts. -->
      <div id="bump"><div id="cam" data-layout-allow-overflow>
{chr(10).join(vids)}
      </div></div>
      <div id="scrim" data-layout-ignore></div>

{chr(10).join(hosts)}

      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html"
        data-start="{f(CAPTIONS_FROM)}" data-duration="{f(TOTAL - CAPTIONS_FROM)}" data-track-index="3" data-track-kind="captions"
        data-width="1080" data-height="1920" style="z-index:50"></div>

      <!-- Sound effects (bundled Pixabay-licensed library, see assets/sfx/CREDITS.md) -->
{chr(10).join(sfx)}
    </div>

    <script>
      const tl = gsap.timeline({{ paused: true }});
      // Hook: slow push-in while the price is said, a small bump on the price and on the NET stamp.
      tl.set("#cam", {{ scale: 1 }}, 0);
      tl.to("#cam", {{ scale: 1.06, duration: 3.8, ease: "none" }}, 0);
      tl.set("#cam", {{ scale: 1 }}, 3.8);
      // CTA: gentle push-in to the end.
      tl.to("#cam", {{ scale: 1.05, duration: {f(TOTAL - SCENES[-1][1])}, ease: "none" }}, {f(SCENES[-1][1])});
      // Bumps on the price and on the NET stamp (outer wrapper, so they never fight the push).
      tl.set("#bump", {{ scale: 1 }}, 0);
      tl.to("#bump", {{ scale: 1.03, duration: 0.08, ease: "power2.out" }}, 1.4);
      tl.to("#bump", {{ scale: 1, duration: 0.3, ease: "power2.inOut" }}, 1.48);
      tl.to("#bump", {{ scale: 1.035, duration: 0.07, ease: "power3.out" }}, 3.45);
      tl.to("#bump", {{ scale: 1, duration: 0.3, ease: "power2.out" }}, 3.52);
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w").write(page)


def build_captions():
    groups, tweens = [], []
    shown = [c for c in caps if c["start"] >= CAPTIONS_FROM - 0.01]
    for k, c in enumerate(shown):
        words = []
        for w in c["text"].split(" "):
            cls = "w hl" if w in c["hl"] else "w"
            words.append(f'<span class="{cls}">{html.escape(w)}</span>')
        size = min(70, int(1480 / max(len(c["text"]), 1)))
        groups.append(f'    <div id="{c["id"]}" class="cg" style="font-size:{size}px">{"&nbsp;".join(words)}</div>')
        a = c["start"] - CAPTIONS_FROM - 0.05
        nxt = shown[k + 1]["start"] - CAPTIONS_FROM - 0.05 if k + 1 < len(shown) else 1e9
        end = min(c["end"] - CAPTIONS_FROM + 0.3, nxt, TOTAL - CAPTIONS_FROM - 0.02)
        a = max(a, 0.0)
        hl_tw = (f'    tl.fromTo("#{c["id"]} .hl", {{ scale: 1 }}, {{ scale: 1.08, duration: 0.12, ease: "power2.out" }}, {f(a + 0.06)});\n'
                 if c["hl"] else "")
        tweens.append(
            f'    tl.fromTo("#{c["id"]}", {{ opacity: 0, scale: 0.86, y: 14 }}, {{ opacity: 1, scale: 1, y: 0, duration: 0.14, ease: "back.out(2.2)" }}, {f(a)});\n'
            + hl_tw +
            f'    tl.to("#{c["id"]}", {{ opacity: 0, duration: 0.08, ease: "power2.in" }}, {f(end - 0.08)});\n'
            f'    tl.set("#{c["id"]}", {{ opacity: 0, visibility: "hidden" }}, {f(end)});'
        )
    page = f"""<template>
  <!-- GENERATED by tools/build.py: caption groups, timed to the cut. -->
  <style>
    #root {{ position: absolute; inset: 0; pointer-events: none; }}
    #root .cg {{ position: absolute; left: 0; top: 560px; width: 1080px; padding: 0 70px; text-align: center;
      font-family: "Montserrat", sans-serif; font-weight: 800; line-height: 1.15; color: #fff; opacity: 0;
      overflow: visible; -webkit-text-stroke: 12px #0b0d12; paint-order: stroke fill;
      text-shadow: 0 6px 18px rgba(0,0,0,.45); }}
    #root .w {{ display: inline-block; margin: 0 0.08em; }}
    #root .hl {{ color: #ffc93c; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920">
{chr(10).join(groups)}
  </div>
  <script>
    const tl = gsap.timeline({{ paused: true }});
{chr(10).join(tweens)}
    window.__timelines = window.__timelines || {{}};
    window.__timelines["captions"] = tl;
  </script>
</template>
"""
    os.makedirs(os.path.join(ROOT, "compositions"), exist_ok=True)
    open(os.path.join(ROOT, "compositions", "captions.html"), "w").write(page)


if __name__ == "__main__":
    build_index()
    build_captions()
    for s in SCENES:
        print(f"scene {s[0]:8s} {s[1]:6.2f} -> {s[2]:6.2f}  ({s[2]-s[1]:.2f}s)")
    print("total", TOTAL)
